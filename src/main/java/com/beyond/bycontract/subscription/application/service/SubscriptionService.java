package com.beyond.bycontract.subscription.application.service;

import com.beyond.bycontract.subscription.application.dto.FacturationInformationsResponse;
import com.beyond.bycontract.subscription.application.dto.InvoiceResponse;
import com.beyond.bycontract.subscription.application.dto.SubscriptionStatusResponse;
import com.beyond.bycontract.subscription.application.port.PaymentGateway;
import com.beyond.bycontract.user.domain.exception.UserNotFoundException;
import com.beyond.bycontract.user.domain.model.User;
import com.beyond.bycontract.user.domain.repository.UserRepository;
import com.stripe.exception.StripeException;
import com.stripe.model.*;
import com.stripe.model.billingportal.Session;
import com.stripe.param.CustomerCreateParams;
import com.stripe.param.CustomerUpdateParams;
import com.stripe.param.InvoiceListParams;
import com.stripe.param.SubscriptionUpdateParams;
import com.stripe.param.billingportal.SessionCreateParams;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.*;

@Service
@RequiredArgsConstructor
@Slf4j
public class SubscriptionService {

    private final PaymentGateway paymentGateway;
    private  final UserRepository userRepository;

    public String createCheckoutSession(UUID idUser, String idPrice, String successUrl, String cancelUrl) {
        User user = userRepository.getUserById(idUser).orElseThrow(() -> new UserNotFoundException(idUser));
        if("active".equals(user.getStripeSubscriptionStatus())) {
            throw new IllegalStateException("L'utilisateur possède déjà un abonnement actif.");
        }

        return paymentGateway.createCheckoutSession(user.getId(), user.getEmail(), user.getStripeIdCustomer(), idPrice,  successUrl, cancelUrl);
    }

    public String createCustomerPortalSession(UUID idUser, String returnUrl) {
        User user = userRepository.getUserById(idUser).orElseThrow(() -> new UserNotFoundException(idUser));
        String stripeIdCustomer = user.getStripeIdCustomer();
        if (stripeIdCustomer == null) {
            throw new RuntimeException("Cet utilisateur n'a pas encore de profil de facturation Stripe");
        }

        try {
            SessionCreateParams params = SessionCreateParams.builder()
                    .setCustomer(stripeIdCustomer)
                    //L URL vers lequel Stripe renverra l utilisateur quand il cliquera sur Retour a BYCONTRACT
                    .setReturnUrl(returnUrl)
                    .build();

            Session portalSession = Session.create(params);

            //Return the URL generated by Stripe
            return portalSession.getUrl();
        }catch (StripeException e) {
            log.error("Erreur de la creation du portail client Stripe pour {}", stripeIdCustomer, e);
            throw new RuntimeException("Impossible d ouvrir le portail de facturation Stripe");
        }
    }

    public SubscriptionStatusResponse getSubscriptionData(UUID idUser) {
        User user = userRepository.getUserById(idUser).orElseThrow(() -> new UserNotFoundException(idUser));
        String status = user.getStripeSubscriptionStatus() != null ? user.getStripeSubscriptionStatus() : "inactive";

        if(user.isTrialExpired()) {
            status = "trial_expired";
        }

        Long periodEnd = user.getCurrentPeriodEnd();
        LocalDateTime currentPeriodEnd = periodEnd != null ? LocalDateTime.ofInstant(Instant.ofEpochSecond(periodEnd), ZoneOffset.UTC): null;

        return new SubscriptionStatusResponse(status, user.getTrialEndDate(), user.getCardBrand(), user.getCardLast4(), user.getPlanName(), user.getPlanPrice(), currentPeriodEnd);
    }

    public List<InvoiceResponse> getUserInvoices(UUID idUser) {
        User user = userRepository.getUserById(idUser)
                .orElseThrow(() -> new UserNotFoundException(idUser));

        // Si l'utilisateur n'est pas encore client Stripe (ex: essai gratuit), on renvoie une liste vide
        if (user.getStripeIdCustomer() == null || user.getStripeIdCustomer().isBlank()) {
            return Collections.emptyList();
        }

        try {
            InvoiceListParams params = InvoiceListParams.builder()
                    .setCustomer(user.getStripeIdCustomer())
                    .setLimit(24L) // Les 24 dernières factures (2 ans en mensuel)
                    .build();

            InvoiceCollection invoices = Invoice.list(params);

            return invoices.getData().stream()
                    .filter(invoice -> !"draft".equals(invoice.getStatus())) // Ignore les brouillons en cours
                    .map(this::mapToDto)
                    .toList();

        } catch (StripeException e) {
            log.error("Erreur lors de la récupération des factures Stripe pour l'utilisateur {}", idUser, e);
            throw new RuntimeException("Impossible de récupérer l'historique de facturation.", e);
        }
    }

    private InvoiceResponse mapToDto(Invoice invoice) {
        LocalDateTime date = invoice.getCreated() != null
                ? LocalDateTime.ofInstant(Instant.ofEpochSecond(invoice.getCreated()), ZoneOffset.UTC)
                : null;

        // getTotal() reflète le montant final TTC de la facture (en centimes)
        Double amount = invoice.getTotal() != null ? invoice.getTotal() / 100.0 : 0.0;

        return new InvoiceResponse(
                invoice.getId(),
                invoice.getNumber(),
                date,
                amount,
                invoice.getCurrency(),
                invoice.getStatus(),
                invoice.getInvoicePdf(),
                invoice.getHostedInvoiceUrl()
        );
    }

    @Transactional
    public void cancelSubscription(UUID userId) {
        updateCancelAtPeriodEnd(userId, true);
    }

    @Transactional
    public void reactivateSubscription(UUID userId) {
        updateCancelAtPeriodEnd(userId, false);
    }

    private void updateCancelAtPeriodEnd(UUID userId, boolean cancelAtPeriodEnd) {
        // Utilise ta méthode avec PESSIMISTIC_WRITE pour éviter les conflits avec les webhooks
        User user = userRepository.getUserById(userId)
                .orElseThrow(() -> new UserNotFoundException(userId));

        if (user.getStripeIdSubscription() == null || user.getStripeIdSubscription().isBlank()) {
            throw new IllegalStateException("Aucun abonnement Stripe associé à cet utilisateur.");
        }

        // Garde-fous métier
        String currentStatus = user.getStripeSubscriptionStatus();
        if ("canceled".equals(currentStatus)) {
            throw new IllegalStateException("Cet abonnement est déjà expiré. Veuillez souscrire à nouveau.");
        }
        if (cancelAtPeriodEnd && "cancel_at_period_end".equals(currentStatus)) {
            return; // Déjà en cours d'annulation (idempotent)
        }
        if (!cancelAtPeriodEnd && "active".equals(currentStatus)) {
            return; // Déjà actif (idempotent)
        }

        try {
            Subscription subscription = Subscription.retrieve(user.getStripeIdSubscription());

            SubscriptionUpdateParams params = SubscriptionUpdateParams.builder()
                    .setCancelAtPeriodEnd(cancelAtPeriodEnd)
                    .build();

            subscription.update(params);

            // Mise à jour immédiate en base pour une UX instantanée
            user.updateSubscriptionStatus(cancelAtPeriodEnd ? "cancel_at_period_end" : "active");
            userRepository.updateUser(user);

        } catch (StripeException e) {
            log.error("Erreur Stripe lors de la mise à jour de l'abonnement pour l'utilisateur {}", userId, e);
            throw new RuntimeException("Impossible de modifier l'abonnement auprès de Stripe.", e);
        }
    }

    public FacturationInformationsResponse getFacturationInformations(UUID userId) {
        User user = userRepository.getUserById(userId)
                .orElseThrow(() -> new UserNotFoundException(userId));

        if (user.getStripeIdCustomer() == null || user.getStripeIdCustomer().isBlank()) {
            return new FacturationInformationsResponse("", user.getEmail(), "", "", "", "", "FR");
        }

        try {
            Customer customer = Customer.retrieve(user.getStripeIdCustomer());
            Address addr = customer.getAddress();

            return new FacturationInformationsResponse(
                    customer.getName() != null ? customer.getName() : "",
                    customer.getEmail() != null ? customer.getEmail() : user.getEmail(),
                    addr != null && addr.getLine1() != null ? addr.getLine1() : "",
                    addr != null && addr.getLine2() != null ? addr.getLine2() : "",
                    addr != null && addr.getCity() != null ? addr.getCity() : "",
                    addr != null && addr.getPostalCode() != null ? addr.getPostalCode() : "",
                    addr != null && addr.getCountry() != null ? addr.getCountry() : "FR"
            );
        } catch (StripeException e) {
            log.error("Erreur lors de la récupération des infos de facturation pour {}", userId, e);
            throw new RuntimeException("Impossible de récupérer les informations de facturation.", e);
        }
    }

    @Transactional
    public FacturationInformationsResponse updateFacturationInformations(UUID userId, FacturationInformationsResponse dto) {
        User user = userRepository.getUserByIdWithLock(userId)
                .orElseThrow(() -> new UserNotFoundException(userId));

        try {
            // Si l'utilisateur n'a pas encore de profil client Stripe, on le crée
            if (user.getStripeIdCustomer() == null || user.getStripeIdCustomer().isBlank()) {
                CustomerCreateParams createParams = CustomerCreateParams.builder()
                        .setName(dto.name())
                        .setEmail(dto.email())
                        .setAddress(CustomerCreateParams.Address.builder()
                                .setLine1(dto.line1())
                                .setLine2(dto.line2() != null ? dto.line2() : "")
                                .setCity(dto.city())
                                .setPostalCode(dto.postalCode())
                                .setCountry(dto.country().toUpperCase())
                                .build())
                        .build();

                Customer newCustomer = Customer.create(createParams);
                user.updateIdCustomer(newCustomer.getId());
                userRepository.updateUser(user);
                return dto;
            }

            // Sinon, on met à jour le client existant
            Customer customer = Customer.retrieve(user.getStripeIdCustomer());
            CustomerUpdateParams updateParams = CustomerUpdateParams.builder()
                    .setName(dto.name())
                    .setEmail(dto.email())
                    .setAddress(CustomerUpdateParams.Address.builder()
                            .setLine1(dto.line1())
                            .setLine2(dto.line2() != null ? dto.line2() : "")
                            .setCity(dto.city())
                            .setPostalCode(dto.postalCode())
                            .setCountry(dto.country().toUpperCase())
                            .build())
                    .build();

            customer.update(updateParams);
            return dto;

        } catch (StripeException e) {
            log.error("Erreur lors de la mise à jour des infos de facturation pour {}", userId, e);
            throw new RuntimeException("Impossible de mettre à jour les informations de facturation.", e);
        }
    }
}
